package opener

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const (
	// AppName is the generated URL-handler app's bundle name.
	AppName = "ImoogiAnki.app"
	// BundleID identifies the generated app; it is also how Install
	// recognizes an app it may replace.
	BundleID = "io.github.karohani.imoogi-anki.url-handler"

	osacompileCommand = "/usr/bin/osacompile"
	codesignCommand   = "/usr/bin/codesign"
	lsregisterCommand = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"

	toolTimeout = 60 * time.Second
)

// InstallOptions configure Install.
type InstallOptions struct {
	// Dest is the directory the app is created in (default ~/Applications).
	Dest string
	// BinaryPath is the absolute imoogi-anki path the app runs. It is fixed
	// into the app at generation time; the app never consults PATH.
	BinaryPath string
	// Register runs lsregister on the result. Off, generation is complete
	// and testable without touching Launch Services (REQ-ASRC-013.2).
	Register bool
	Run      Runner
}

// DefaultInstallDest is ~/Applications.
func DefaultInstallDest() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, "Applications"), nil
}

// CurrentBinary is the running imoogi-anki's absolute, symlink-resolved path,
// the value the app is generated around.
func CurrentBinary() (string, error) {
	return executablePath()
}

func resolveSymlinks(path string) (string, error) {
	abs, err := filepath.Abs(path)
	if err != nil {
		return "", err
	}
	return filepath.EvalSymlinks(abs)
}

// AppleScriptSource is the URL handler's script. The binary path and the URL
// are each shell-quoted with `quoted form of`, so a path with spaces stays one
// argument; the binary validates the URL again on its own (REQ-ASRC-013.1).
//
// The binary notifies about its own failures and exits 1 or 2; those are not
// shown twice. Any other failure — the binary moved or is not executable —
// would otherwise be invisible, so it raises an alert.
func AppleScriptSource(binaryPath string) string {
	return `-- Generated by "imoogi-anki install-url-handler" (SPEC-ANKISRC-001).
-- Hands imoogi-anki:// links to the imoogi-anki binary fixed below.
on open location theURL
	try
		do shell script (quoted form of ` + appleScriptString(binaryPath) + `) & " open " & (quoted form of theURL)
	on error errMsg number errNum
		if errNum is not 1 and errNum is not 2 then
			display alert "imoogi-anki" message errMsg as critical
		end if
	end try
end open location

on run
	display alert "imoogi-anki" message "이 앱은 Anki 카드의 'Emacs에서 원본 열기' 링크를 처리합니다. 직접 실행할 필요는 없습니다."
end run
`
}

// InfoPlist is the app's Info.plist: osacompile's own applet keys plus the
// bundle identifier, the imoogi-anki URL scheme, and LSUIElement so the
// handler never shows a Dock icon.
func InfoPlist() string {
	return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleAllowMixedLocalizations</key>
	<true/>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleExecutable</key>
	<string>applet</string>
	<key>CFBundleIconFile</key>
	<string>applet</string>
	<key>CFBundleIdentifier</key>
	<string>` + BundleID + `</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>ImoogiAnki</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleSignature</key>
	<string>aplt</string>
	<key>CFBundleURLTypes</key>
	<array>
		<dict>
			<key>CFBundleURLName</key>
			<string>imoogi-anki open-source link</string>
			<key>CFBundleURLSchemes</key>
			<array>
				<string>` + Scheme + `</string>
			</array>
		</dict>
	</array>
	<key>LSUIElement</key>
	<true/>
	<key>OSAAppletShowStartupScreen</key>
	<false/>
</dict>
</plist>
`
}

// Install generates the URL-handler app in opts.Dest and, when asked,
// registers it with Launch Services. It returns the app's path.
//
// An existing app at that path is replaced only when it is one Install made
// (its Info.plist names BundleID); anything else is left alone.
func Install(opts InstallOptions) (string, error) {
	if !filepath.IsAbs(opts.BinaryPath) {
		return "", fmt.Errorf("binary path must be absolute: %q", opts.BinaryPath)
	}
	if opts.Dest == "" {
		dest, err := DefaultInstallDest()
		if err != nil {
			return "", err
		}
		opts.Dest = dest
	}
	app := filepath.Join(opts.Dest, AppName)
	plistPath := filepath.Join(app, "Contents", "Info.plist")

	if _, err := os.Stat(app); err == nil {
		existing, readErr := os.ReadFile(plistPath)
		if readErr != nil || !strings.Contains(string(existing), BundleID) {
			return "", fmt.Errorf("%s exists and was not created by imoogi-anki; move it away first", app)
		}
		if err := os.RemoveAll(app); err != nil {
			return "", err
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", err
	}
	if err := os.MkdirAll(opts.Dest, 0o755); err != nil {
		return "", err
	}

	work, err := os.MkdirTemp("", "imoogi-anki-handler-*")
	if err != nil {
		return "", err
	}
	defer func() { _ = os.RemoveAll(work) }()
	source := filepath.Join(work, "imoogi-anki-url-handler.applescript")
	if err := os.WriteFile(source, []byte(AppleScriptSource(opts.BinaryPath)), 0o600); err != nil {
		return "", err
	}

	if err := runTool(opts.Run, osacompileCommand, "-o", app, source); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(plistPath), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(plistPath, []byte(InfoPlist()), 0o644); err != nil {
		return "", err
	}
	// osacompile signs the applet ad hoc, and rewriting Info.plist breaks that
	// seal; re-sign so the app still launches on Apple silicon.
	if err := runTool(opts.Run, codesignCommand, "--force", "--sign", "-", app); err != nil {
		return "", err
	}
	if opts.Register {
		if err := runTool(opts.Run, lsregisterCommand, "-f", app); err != nil {
			return "", err
		}
	}
	return app, nil
}

func runTool(run Runner, name string, args ...string) error {
	ctx, cancel := context.WithTimeout(context.Background(), toolTimeout)
	defer cancel()
	r := run(ctx, name, args...)
	switch {
	case r.TimedOut || ctx.Err() != nil:
		return fmt.Errorf("%s timed out", filepath.Base(name))
	case r.Err != nil:
		return fmt.Errorf("%s: %v", filepath.Base(name), r.Err)
	case r.ExitCode != 0:
		return fmt.Errorf("%s failed (exit %d): %s", filepath.Base(name), r.ExitCode, firstLine(r.Stderr))
	}
	return nil
}
